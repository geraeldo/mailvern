/** Known provider info if the email's domain is recognized, otherwise null. */
export function detectProvider(email: string): ProviderInfo | null {
  const domain = email.split("@")[1]?.trim().toLowerCase();
  if (!domain || !domain.includes(".")) return null;
  const key = domains[domain];
  if (!key) return null;
  const p = presets[key];
  return { id: key, name: p.name, servers: { ...p.servers }, passwordHint: p.passwordHint };
}

/** Known provider settings, or a conventional imap./smtp. guess for custom domains. */
export function guessServers(email: string): Servers | null {
  const domain = email.split("@")[1]?.trim().toLowerCase();
  if (!domain || !domain.includes(".")) return null;
  const known = domains[domain];
  if (known) return { ...presets[known].servers };
  return { imapHost: `imap.${domain}`, imapPort: 993, smtpHost: `smtp.${domain}`, smtpPort: 465 };
}
